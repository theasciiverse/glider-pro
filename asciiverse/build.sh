#!/bin/sh
# Builds glider-pro (the terminal edition) and its data with notcurses linked
# in statically, so the binary needs no notcurses installed.
#
# GNU libunistring and notcurses (core only, no multimedia) are built from
# source into av-build/, as for Twistty, notcurses with our patches from
# asciiverse/patches (tmux 3.4 and newer would otherwise hang it at start).
# libdeflate and ncurses' terminfo library come from the system as static
# libraries. SDL2 (sound, gamepads) is linked from the system for now.
#
# Output: av-build/install/bin/glider-pro and av-build/install/lib/aerofoil/
# Packaged (the game's data, from Calhoun's files by Aerofoil's tools).
set -eu
NOTCURSES=3.0.17
UNISTRING=1.3
UNISTRING_SHA256=8ea8ccf86c09dd801c8cac19878e804e54f707cf69884371130d20bde68386b7

if [ -f /etc/os-release ] && grep -q '^ID=ubuntu' /etc/os-release && [ "$(id -u)" = 0 ]; then
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq
  apt-get install -y -qq build-essential cmake git curl pkg-config \
    libncurses-dev libdeflate-dev libsdl2-dev libfreetype-dev >/dev/null
fi

root=$(pwd)
deps="$root/av-build"
prefix="$deps/prefix"
mkdir -p "$deps"
jobs=$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)

if [ ! -f "$prefix/lib/libunistring.a" ]; then
  tarball="$deps/libunistring-$UNISTRING.tar.gz"
  [ -f "$tarball" ] || curl -sSL -o "$tarball" "https://ftp.gnu.org/gnu/libunistring/libunistring-$UNISTRING.tar.gz"
  echo "$UNISTRING_SHA256  $tarball" | sha256sum -c - >/dev/null
  rm -rf "$deps/libunistring-$UNISTRING"
  tar -xzf "$tarball" -C "$deps"
  (cd "$deps/libunistring-$UNISTRING" &&
    ./configure -q --prefix="$prefix" --disable-shared --enable-static --with-pic >/dev/null &&
    make -s -j "$jobs" >/dev/null && make -s install >/dev/null)
fi

if [ ! -f "$prefix/lib/libnotcurses-core.a" ]; then
  if [ ! -d "$deps/notcurses" ]; then
    git clone -q --depth 1 -b "v$NOTCURSES" https://github.com/dankamongmen/notcurses "$deps/notcurses"
  fi
  git -C "$deps/notcurses" checkout -q -- .
  for p in "$root"/asciiverse/patches/notcurses-*.patch; do
    git -C "$deps/notcurses" apply "$p"
  done
  cmake -S "$deps/notcurses" -B "$deps/notcurses-build" -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_INSTALL_PREFIX="$prefix" -DCMAKE_PREFIX_PATH="$prefix" \
    -DCMAKE_C_FLAGS="-I$prefix/include" -DCMAKE_EXE_LINKER_FLAGS="-L$prefix/lib" \
    -DUSE_MULTIMEDIA=none -DUSE_CXX=OFF -DUSE_PANDOC=OFF -DUSE_DOCTEST=OFF \
    -DUSE_POC=OFF -DBUILD_EXECUTABLES=OFF -DBUILD_FFI_LIBRARY=OFF \
    -DUSE_STATIC=ON -DUSE_QRCODEGEN=OFF -DUSE_GPM=OFF \
    -Dunistring="$prefix/lib/libunistring.a" >/dev/null
  cmake --build "$deps/notcurses-build" -j "$jobs" --target notcurses-core-static >/dev/null
  mkdir -p "$prefix/lib" "$prefix/include"
  cp "$deps/notcurses-build/libnotcurses-core.a" "$prefix/lib/"
  rm -rf "$prefix/include/notcurses"
  cp -r "$deps/notcurses/include/notcurses" "$prefix/include/"
  # version.h is generated by the configure step
  cp "$deps/notcurses-build/include/version.h" "$prefix/include/notcurses/" 2>/dev/null || true
fi

static_lib() {
  for d in "$prefix/lib" /usr/lib/x86_64-linux-gnu /usr/lib/aarch64-linux-gnu /usr/lib64 /usr/lib; do
    if [ -f "$d/$1" ]; then
      echo "$d/$1"
      return
    fi
  done
  echo "missing static library $1" >&2
  exit 1
}

# The licence texts of everything linked in, for the release archive
lic="$deps/licenses"
rm -rf "$lic" && mkdir -p "$lic"
cp "$deps/notcurses/COPYRIGHT" "$lic/notcurses.txt"
if [ -d "$deps/libunistring-$UNISTRING" ]; then
  cp "$deps/libunistring-$UNISTRING/COPYING.LIB" "$lic/libunistring-LGPL-3.0.txt"
  cp "$deps/libunistring-$UNISTRING/COPYING" "$lic/libunistring-GPL-3.0.txt"
fi
for pkg in libdeflate-dev:libdeflate libncurses-dev:ncurses; do
  f="/usr/share/doc/${pkg%%:*}/copyright"
  [ -f "$f" ] && cp "$f" "$lic/${pkg##*:}.txt"
done

git submodule update --init zlib/zlib
cmake -S "$root" -B "$deps/build" -DCMAKE_BUILD_TYPE=Release \
  -DCMAKE_INSTALL_PREFIX="$deps/install" -DAV_NOTCURSES_PREFIX="$prefix" >/dev/null
cmake --build "$deps/build" -j "$jobs" --target glider-pro Resources >/dev/null
cmake --install "$deps/build" --component Terminal >/dev/null
cmake --install "$deps/build" --component Resources >/dev/null
strip "$deps/install/bin/glider-pro"
echo "built $deps/install/bin/glider-pro"
